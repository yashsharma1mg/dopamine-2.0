// Inlines the Dopamine SVG assets as data-URIs so the published @dopamine2.0/ui
// package is fully self-contained — components no longer depend on runtime
// /assets/dopamine/* URLs that only exist on the docs site.
//
// Includes the whole icon library (icons/*) plus the assets that shipped
// components reference internally (page-header-*, suggestion-chip-*).
import { readdirSync, readFileSync, writeFileSync, statSync } from "node:fs";
import { join, relative } from "node:path";

const ROOT = new URL("..", import.meta.url).pathname;
const ASSET_DIR = join(ROOT, "public/assets/dopamine");
const SRC_DIR = join(ROOT, "packages/ui/src");
const OUT = join(ROOT, "packages/ui/src/generated/icon-data.ts");

const INCLUDE_TOP_LEVEL = /^(page-header-|suggestion-chip-)/; // referenced by shipped components

function svgFiles(dir) {
  const out = [];
  for (const name of readdirSync(dir)) {
    const full = join(dir, name);
    if (statSync(full).isDirectory()) out.push(...svgFiles(full));
    else if (name.endsWith(".svg")) out.push(full);
  }
  return out;
}

// Collect icons/ names actually referenced via <DsIcon name="…"> in shipped
// component source (DsIcon is internal, so this set is complete and static).
function referencedIconNames() {
  const names = new Set();
  const walk = (dir) => {
    for (const name of readdirSync(dir)) {
      const full = join(dir, name);
      if (statSync(full).isDirectory()) walk(full);
      else if (name.endsWith(".tsx") && !name.endsWith(".stories.tsx")) {
        const src = readFileSync(full, "utf8");
        for (const m of src.matchAll(/<DsIcon\s+name="([^"]+)"/g)) names.add(m[1]);
      }
    }
  };
  walk(SRC_DIR);
  return names;
}

// Strip Figma-export cruft that mask/img rendering does not need, then encode.
function toDataUri(svg) {
  const min = svg
    .replace(/<!--[\s\S]*?-->/g, "")
    .replace(/\s+(preserveAspectRatio|overflow)="[^"]*"/g, "")
    .replace(/\s+style="[^"]*display:\s*block;?[^"]*"/g, "")
    .replace(/\s+/g, " ")
    .replace(/>\s+</g, "><")
    .trim();
  return "data:image/svg+xml," + encodeURIComponent(min);
}

const iconNames = referencedIconNames();
const entries = [];
for (const file of svgFiles(ASSET_DIR).sort()) {
  const key = relative(ASSET_DIR, file).replace(/\.svg$/, "").split("\\").join("/");
  const usedIcon = key.startsWith("icons/") && iconNames.has(key.slice("icons/".length));
  const topLevel = !key.includes("/") && INCLUDE_TOP_LEVEL.test(key);
  if (!usedIcon && !topLevel) continue;
  entries.push([key, toDataUri(readFileSync(file, "utf8"))]);
}

const body = entries.map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)}`).join(",\n");
writeFileSync(
  OUT,
  `// AUTO-GENERATED by scripts/generate-icon-data.mjs — do not edit by hand.\n` +
    `// Dopamine SVG assets inlined as data-URIs so the package ships self-contained.\n` +
    `export const iconData: Record<string, string> = {\n${body}\n};\n`
);
console.log(`Inlined ${entries.length} icon assets → ${relative(ROOT, OUT)}`);
